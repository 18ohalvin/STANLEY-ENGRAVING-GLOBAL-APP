// Helper to calculate exact geometric bounding box of any SVG elements
function computeSvgBoundingBox(svgBody: string): { x: number, y: number, width: number, height: number } {
  let minX = Infinity
  let minY = Infinity
  let maxX = -Infinity
  let maxY = -Infinity

  const updateBounds = (x: number, y: number, pad = 0) => {
    if (isNaN(x) || isNaN(y)) return
    minX = Math.min(minX, x - pad)
    maxX = Math.max(maxX, x + pad)
    minY = Math.min(minY, y - pad)
    maxY = Math.max(maxY, y + pad)
  }

  const circleRegex = /<circle[^>]*cx=["']([\d.-]+)["'][^>]*cy=["']([\d.-]+)["'][^>]*r=["']([\d.-]+)["']/g
  let match: RegExpExecArray | null
  while ((match = circleRegex.exec(svgBody)) !== null) {
    const cx = parseFloat(match[1])
    const cy = parseFloat(match[2])
    const r = parseFloat(match[3])
    updateBounds(cx - r, cy - r)
    updateBounds(cx + r, cy + r)
  }

  const ellipseRegex = /<ellipse[^>]*cx=["']([\d.-]+)["'][^>]*cy=["']([\d.-]+)["'][^>]*rx=["']([\d.-]+)["'][^>]*ry=["']([\d.-]+)["']/g
  while ((match = ellipseRegex.exec(svgBody)) !== null) {
    const cx = parseFloat(match[1])
    const cy = parseFloat(match[2])
    const rx = parseFloat(match[3])
    const ry = parseFloat(match[4])
    updateBounds(cx - rx, cy - ry)
    updateBounds(cx + rx, cy + ry)
  }

  const rectRegex = /<rect[^>]*x=["']([\d.-]+)["'][^>]*y=["']([\d.-]+)["'][^>]*width=["']([\d.-]+)["'][^>]*height=["']([\d.-]+)["']/g
  while ((match = rectRegex.exec(svgBody)) !== null) {
    const x = parseFloat(match[1])
    const y = parseFloat(match[2])
    const w = parseFloat(match[3])
    const h = parseFloat(match[4])
    updateBounds(x, y)
    updateBounds(x + w, y + h)
  }

  const lineRegex = /<line[^>]*x1=["']([\d.-]+)["'][^>]*y1=["']([\d.-]+)["'][^>]*x2=["']([\d.-]+)["'][^>]*y2=["']([\d.-]+)["']/g
  while ((match = lineRegex.exec(svgBody)) !== null) {
    const x1 = parseFloat(match[1])
    const y1 = parseFloat(match[2])
    const x2 = parseFloat(match[3])
    const y2 = parseFloat(match[4])
    updateBounds(x1, y1)
    updateBounds(x2, y2)
  }

  const polyRegex = /<(?:polygon|polyline)[^>]*points=["']([^"']+)["']/g
  while ((match = polyRegex.exec(svgBody)) !== null) {
    const pts = match[1].trim().split(/[\s,]+/)
    for (let i = 0; i < pts.length - 1; i += 2) {
      updateBounds(parseFloat(pts[i]), parseFloat(pts[i + 1]))
    }
  }

  const pathRegex = /<path[^>]*d=["']([^"']+)["']/g
  while ((match = pathRegex.exec(svgBody)) !== null) {
    const d = match[1]
    const tokens = d.match(/[a-df-z]|[-+]?(?:\d*\.\d+|\d+)/gi) || []
    let curX = 0
    let curY = 0
    let i = 0
    while (i < tokens.length) {
      const token = tokens[i]
      if (/^[a-df-z]$/i.test(token)) {
        const cmd = token
        i++
        if (cmd === 'M' || cmd === 'L' || cmd === 'T') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curX = parseFloat(tokens[i++])
            curY = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'm' || cmd === 'l' || cmd === 't') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curX += parseFloat(tokens[i++])
            curY += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'H') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curX = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'h') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curX += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'V') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curY = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'v') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            curY += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'C') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 4
            curX = parseFloat(tokens[i++])
            curY = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'c') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 4
            curX += parseFloat(tokens[i++])
            curY += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'S' || cmd === 'Q') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 2
            curX = parseFloat(tokens[i++])
            curY = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 's' || cmd === 'q') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 2
            curX += parseFloat(tokens[i++])
            curY += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'A') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 5
            curX = parseFloat(tokens[i++])
            curY = parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        } else if (cmd === 'a') {
          while (i < tokens.length && !/^[a-df-z]$/i.test(tokens[i])) {
            i += 5
            curX += parseFloat(tokens[i++])
            curY += parseFloat(tokens[i++])
            updateBounds(curX, curY)
          }
        }
      } else {
        i++
      }
    }
  }

  if (!isFinite(minX) || !isFinite(minY) || !isFinite(maxX) || !isFinite(maxY)) {
    return { x: 0, y: 0, width: 100, height: 100 }
  }

  const pad = 1.5
  const finalMinX = Math.max(0, minX - pad)
  const finalMinY = Math.max(0, minY - pad)
  const finalMaxX = maxX + pad
  const finalMaxY = maxY + pad

  return {
    x: Math.round(finalMinX * 10) / 10,
    y: Math.round(finalMinY * 10) / 10,
    width: Math.max(1, Math.round((finalMaxX - finalMinX) * 10) / 10),
    height: Math.max(1, Math.round((finalMaxY - finalMinY) * 10) / 10)
  }
}

// Helper to convert clean SVG content into a tight SVG data URI
function createSvgDataUri(svgBody: string): string {
  const bbox = computeSvgBoundingBox(svgBody)
  const fullSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="4096" height="4096" viewBox="${bbox.x} ${bbox.y} ${bbox.width} ${bbox.height}" preserveAspectRatio="xMidYMid meet" fill="white" shape-rendering="geometricPrecision">${svgBody}</svg>`
  return `data:image/svg+xml;utf8,${encodeURIComponent(fullSvg)}`
}



